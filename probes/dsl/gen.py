"""Generate .omar topology programs for the DSL-arm probes.

Prompts mirror the frozen arm-A postal prompts minus ADDRESS_RULES (the
runtime owns routing).

Usage:
  python3 gen.py chain 100 --backend Stub  > Chain100.omar
  python3 gen.py chain 100 --backend Claude --slice 51:100 > Chain100b.claude.omar
  python3 gen.py ring  10  --backend Claude > Ring10.omar
"""
import argparse


def chain(n, backend, start=1, end=None):
    end = end or n
    sliced = (start, end) != (1, n)
    seg = f", nodes {start}..{end}" if sliced else ""
    out = [f"// DSL-arm chain probe, n={n}{seg}, backend={backend}. Generated by gen.py."]
    out.append(f"team Relay(idx : int, nn : int)[agent : {backend}]")
    out.append("{")
    out.append("    input msg : string")
    out.append("    output fwd : string")
    out.append("")
    out.append("    task agent(msg) -> fwd")
    out.append('    "')
    out.append("        You are node $(idx) of $(nn) in a relay chain. Chain protocol:")
    out.append("        append 'node $(idx)' to the trail, keep every existing payload")
    out.append("        field and trail entry intact, and pass the full updated message")
    out.append("        onward by setting `fwd`.")
    out.append("        You received:")
    out.append("")
    out.append("        $(msg)")
    out.append('    "')
    out.append("}")
    out.append("")
    name = f"Chain{n}seg{start}to{end}" if sliced else f"Chain{n}"
    out.append(f"main {name} {{")
    for i in range(start, end + 1):
        out.append(f"    r{i} = Relay({i}, {n})")
    for i in range(start, end):
        out.append(f"    r{i}.fwd -> r{i + 1}.msg")
    out.append("}")
    return "\n".join(out) + "\n"


def ring(n, backend):
    out = [f"// DSL-arm ring probe, n={n}, backend={backend}. Generated by gen.py."]
    out.append("// Termination is agent-decided via (fwd | done); no runtime bounds yet.")
    out.append(f"team RingNode(idx : int, nn : int)[agent : {backend}]")
    out.append("{")
    out.append("    input msg : string")
    out.append("    output fwd : string")
    out.append("    output done : string")
    out.append("")
    out.append("    task agent(msg) -> (fwd | done)")
    out.append('    "')
    out.append("        You are node $(idx) of $(nn) in a message-passing ring. Ring")
    out.append("        protocol: append 'node $(idx)' to the trail, then pass the full")
    out.append("        updated message to your successor by setting `fwd`. The task")
    out.append("        inside the message says how long the ring should keep")
    out.append("        circulating; you decide whether to keep passing (set `fwd`) or")
    out.append("        to finish the whole run (set `done` to the final message).")
    out.append("        Set exactly one, never both.")
    out.append("        You received:")
    out.append("")
    out.append("        $(msg)")
    out.append('    "')
    out.append("}")
    out.append("")
    out.append(f"main Ring{n} {{")
    for i in range(1, n + 1):
        out.append(f"    r{i} = RingNode({i}, {n})")
    for i in range(1, n):
        out.append(f"    r{i}.fwd -> r{i + 1}.msg")
    out.append(f"    r{n}.fwd -> r1.msg")
    out.append("}")
    return "\n".join(out) + "\n"


RING_JUDGED_PROMPT = '''    task agent(m{k}) -> (fwd{k} | done{k})
    "
        You are node $(idx) of $(nn) in a message-passing ring. Ring
        protocol: append 'node $(idx)' to the trail, then pass the full
        updated message to your successor by setting `fwd{k}`. The task
        inside the message says how long the ring should keep
        circulating; you decide whether to keep passing (set `fwd{k}`) or
        to finish the whole run (set `done{k}` to the final message).
        Set exactly one, never both.
        You received:

        $(m{k})
    "'''

RING_BOUNDED_PROMPT = '''    task agent(m{k}) -> fwd{k}
    "
        You are node $(idx) of $(nn) in a message-passing ring. Ring
        protocol: append 'node $(idx)' to the trail, then pass the full
        updated message to your successor by setting `fwd{k}`.
        You received:

        $(m{k})
    "'''


def ring_unrolled(n, backend, laps, judged):
    # 2n-hop horizon as wiring (arm A used --max-messages 2n): lap k has its
    # own port pair; the last wrap edge has nowhere to go. Same agents revisit.
    mode = "judged" if judged else "bounded"
    out = [f"// DSL-arm ring probe ({mode}), n={n}, laps={laps}, backend={backend}. Generated by gen.py."]
    out.append(f"team RingNode(idx : int, nn : int)[agent : {backend}]")
    out.append("{")
    for k in range(1, laps + 1):
        out.append(f"    input m{k} : string")
    for k in range(1, laps + 1):
        out.append(f"    output fwd{k} : string")
    if judged:
        for k in range(1, laps + 1):
            out.append(f"    output done{k} : string")
    tmpl = RING_JUDGED_PROMPT if judged else RING_BOUNDED_PROMPT
    for k in range(1, laps + 1):
        out.append("")
        out.append(tmpl.format(k=k))
    out.append("}")
    out.append("")
    out.append(f"main Ring{'J' if judged else 'B'}{n} {{")
    for i in range(1, n + 1):
        out.append(f"    r{i} = RingNode({i}, {n})")
    for k in range(1, laps + 1):
        for i in range(1, n):
            out.append(f"    r{i}.fwd{k} -> r{i + 1}.m{k}")
        if k < laps:
            out.append(f"    r{n}.fwd{k} -> r1.m{k + 1}")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("kind", choices=["chain", "ring", "ring-judged", "ring-bounded"])
    p.add_argument("n", type=int)
    p.add_argument("--backend", default="Stub")
    p.add_argument("--slice", help="START:END node range, chain only")
    p.add_argument("--laps", type=int, default=2)
    a = p.parse_args()
    if a.slice and a.kind != "chain":
        p.error("--slice applies to chain only")
    start, end = (int(x) for x in a.slice.split(":")) if a.slice else (1, a.n)
    if a.kind == "chain":
        print(chain(a.n, a.backend, start, end), end="")
    elif a.kind == "ring":
        print(ring(a.n, a.backend), end="")
    else:
        print(ring_unrolled(a.n, a.backend, a.laps, a.kind == "ring-judged"), end="")
